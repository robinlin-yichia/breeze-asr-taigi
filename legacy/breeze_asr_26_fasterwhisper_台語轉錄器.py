class GPUOptimizer:
    @staticmethod
    def detect() -> Tuple[str, str, int]:
        """回傳 (device, compute_type, batch_size)"""
        if not torch.cuda.is_available():
            print("⚠️ 未偵測到 GPU，使用 CPU 模式 (較慢)")
            return "cpu", "int8", 1

        gpu_name = torch.cuda.get_device_name(0)
        vram = torch.cuda.get_device_properties(0).total_memory / (1024**3)
        print(f"🔍 偵測到 GPU: {gpu_name} (VRAM: {vram:.1f} GB)")

        if vram >= 38:
            compute_type, batch_size = "float16", 24
        elif vram >= 22:
            compute_type, batch_size = "float16", 16
        elif vram >= 14:
            compute_type, batch_size = "float16", 8
        else:
            compute_type, batch_size = "int8_float16", 4

        print(f"✅ 配置: 精度={compute_type}, 批次量={batch_size}")
        return "cuda", compute_type, batch_size

