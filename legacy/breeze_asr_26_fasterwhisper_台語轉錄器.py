def main(output_srt: bool = True):
    print("\n" + "="*65)
    print("🇹🇼 台灣台語語音轉文字轉錄器 v8.0 (Faster-Whisper 直載版)")
    print("   Powered by Breeze-ASR-26 × CTranslate2 × Beam Search")
    print("="*65)

    wav_path = None
    asr = None
    executor = None

    try:
        # 步驟 1: GPU 偵測
        print("\n[步驟 1/5] 硬體資源配置")
        device, compute_type, batch_size = GPUOptimizer.detect()

        # 步驟 2: 背景載入模型 + 等待上傳
        print("\n[步驟 2/5] 載入預轉換 CT2 模型 (首次需下載 ~2.9 GB)")
        asr = BreezeASR(device, compute_type, batch_size)
        executor = ThreadPoolExecutor(max_workers=2)
        model_future = executor.submit(asr.load)

        print("\n⚡ 系統正在背景下載並載入模型...")
        print("💡 請現在上傳您的台語音檔，兩者將並行處理！\n")

        if IN_COLAB:
            uploaded = files.upload()
            if not uploaded:
                print("❌ 操作取消：未選擇任何檔案。")
                return
            src_path = list(uploaded.keys())[0]
        else:
            src_path = input("請輸入音檔本機路徑: ")
            if not os.path.exists(src_path):
                print("❌ 錯誤：找不到該檔案。")
                return

        print(f"\n✅ 成功接收檔案: {src_path}")
        print(f"   目前模型狀態: {asr.get_status()}")

        # 步驟 3: 轉換音檔
        print("\n[步驟 3/5] 音檔前處理")
        wav_path, duration = AudioConverter.convert(src_path)

        # 步驟 4: 等待模型並轉錄
        print("\n[步驟 4/5] 語音辨識與時間戳對齊")
        if not asr.is_loaded():
            print("⏳ 正在等待模型載入...")
            while not asr.is_loaded():
                print(f"\r   狀態: {asr.get_status()}        ", end="", flush=True)
                time.sleep(1)
            print()

        model_future.result()
        segments = asr.transcribe(wav_path)

        # 步驟 5: 儲存與下載
        print("\n[步驟 5/5] 封裝與輸出")
        txt_path, srt_path = save_transcript(segments, src_path, output_srt)

        if txt_path and segments:
            print("\n" + "="*65)
            print("📝 轉錄結果預覽 (前 8 段)")
            print("="*65)
            for seg in segments[:8]:
                print(seg.to_timestamp_line())
            if len(segments) > 8:
                print(f"\n... (共 {len(segments)} 段，完整內容請參閱下載檔案) ...")
            print("="*65)

            if IN_COLAB:
                print("\n📥 正在觸發瀏覽器下載...")
                files.download(txt_path)
                if srt_path:
                    files.download(srt_path)

        print("\n✨ 任務圓滿完成，感謝您的使用！")

    except Exception as e:
        print(f"\n❌ 發生未預期的系統錯誤: {e}")
        import traceback
        traceback.print_exc()

    finally:
        if wav_path and os.path.exists(wav_path):
            try:
                os.remove(wav_path)
                print("\n🧹 已清理暫存音檔")
            except Exception:
                pass
        if executor:
            executor.shutdown(wait=False)
        if asr and asr.model:
            del asr.model
            del asr.batched_model
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
        gc.collect()

if __name__ == "__main__":
    main(output_srt=True)