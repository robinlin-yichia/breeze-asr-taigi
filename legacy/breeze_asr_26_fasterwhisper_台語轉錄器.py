class BreezeASR:
    # 使用社群預轉換的 CTranslate2 模型，省去轉換等待
    MODEL_ID = "paulpengtw/faster-whisper-Breeze-ASR-26"

    def __init__(self, device: str, compute_type: str, batch_size: int):
        self.device = device
        self.compute_type = compute_type
        self.batch_size = batch_size
        self.model = None
        self.batched_model = None
        self._is_loaded = False
        self._load_status = "等待初始化"
        self._load_lock = threading.Lock()

    def load(self) -> 'BreezeASR':
        """載入預轉換的 CTranslate2 模型"""
        with self._load_lock:
            if self._is_loaded:
                return self
            try:
                self._load_status = "正在從 HuggingFace 下載 CT2 模型 (~2.9 GB)..."
                self.model = WhisperModel(
                    self.MODEL_ID,
                    device=self.device,
                    compute_type=self.compute_type,
                    cpu_threads=os.cpu_count() or 4,
                )

                self._load_status = "正在構建批次推論管線..."
                self.batched_model = BatchedInferencePipeline(model=self.model)

                self._is_loaded = True
                self._load_status = "載入完成"
            except Exception as e:
                self._load_status = f"載入失敗: {str(e)}"
                raise e
            return self

    def is_loaded(self) -> bool:
        return self._is_loaded

    def get_status(self) -> str:
        return self._load_status

    def transcribe(self, wav_path: str, use_vad: bool = True) -> List[TimestampedSegment]:
        """
        使用 BatchedInferencePipeline 進行批次轉錄。
        beam_size=5 提升辨識精確度 (與 HF Pipeline 的 Greedy Decoding 相比)。
        """
        print("\n🎤 啟動 Faster-Whisper 語音辨識引擎...")
        start_time = time.time()

        is_running = True

        def display_timer():
            while is_running:
                elapsed = int(time.time() - start_time)
                mins, secs = divmod(elapsed, 60)
                print(f"\r   ⏳ 引擎運算中... [{mins:02d}:{secs:02d}]", end="", flush=True)
                time.sleep(1)

        timer_thread = threading.Thread(target=display_timer)
        timer_thread.start()

        segments_out: List[TimestampedSegment] = []

        try:
            segments_iter, info = self.batched_model.transcribe(
                wav_path,
                batch_size=self.batch_size,
                language="zh",           # 強制指定中文，避免語言偵測開銷
                beam_size=5,             # Beam Search 提升精確度
                vad_filter=use_vad,
                vad_parameters=dict(
                    min_silence_duration_ms=500,
                    speech_pad_ms=200,
                ),
                word_timestamps=False,
                without_timestamps=False,
            )

            for seg in segments_iter:
                text = seg.text.strip()
                if not text:
                    continue
                start_t = seg.start if seg.start is not None else 0.0
                end_t = seg.end if seg.end is not None else start_t + 1.0
                segments_out.append(TimestampedSegment(
                    start_time=start_t,
                    end_time=end_t,
                    text=text
                ))

        finally:
            is_running = False
            timer_thread.join()
            print("\r" + " " * 50 + "\r", end="")

        elapsed = time.time() - start_time
        total_chars = sum(len(seg.text) for seg in segments_out)

        print(f"✅ 轉錄完成！")
        print(f"   偵測語言: {info.language} (機率 {info.language_probability:.2%})")
        print(f"   總計耗時: {elapsed:.1f} 秒")
        print(f"   產出片段: {len(segments_out)} 段")
        print(f"   總辨識字數: {total_chars} 字")

        return segments_out

